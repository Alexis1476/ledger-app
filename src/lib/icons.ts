/** The icon to draw for a stored name: a Lucide name becomes its Material Symbol. */
export function materialIcon(name: string): string {
  const m = /^i-lucide-(.+)$/.exec(name)
  const to = m && LUCIDE_TO_MATERIAL[m[1]]
  return to ? `material-symbols:${to}` : name
}
